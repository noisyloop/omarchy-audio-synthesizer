// ---- 3. golden renders --------------------------------------------------------
// Mirrors the browser engine (src/audio/engine.ts): loadPreset -> syncAll.
const tableCache = new Map()
function tableFor(values, osc) {
  const CUSTOM = WAVETABLE_NAMES.indexOf('Custom')
  const sel = Math.round(values[paramIndex(`osc${osc + 1}.wavetable`)] * (WAVETABLE_NAMES.length - 1))
  const name = WAVETABLE_NAMES[Math.min(sel, CUSTOM - 1)] ?? WAVETABLE_NAMES[0]
  if (!tableCache.has(name)) {
    const t = wt.generateWavetable(name)
    tableCache.set(name, { t, mips: wt.buildMips(t.data, t.frameSize, t.numFrames) })
  }
  return tableCache.get(name)
}

function presetFor(c) {
  if (c.preset) {
    const p = FACTORY.find(f => f.name === c.preset)
    if (!p) throw new Error(`unknown preset ${c.preset}`)
    return p
  }
  const ps = {}
  for (const [id, v] of Object.entries(c.raw ?? {})) ps[id] = valueToNorm(params.paramDef(id), v)
  return { name: c.name, params: ps, mods: c.mods ?? [] }
}

function render(c) {
  Math.random = mulberry32(spec.seed)
  const proc = new ProcessorClass()
  const send = msg => proc.port.onmessage({ data: msg })
  const preset = presetFor(c)

  const values = defaultValues()
  for (const [id, v] of Object.entries(preset.params ?? {})) values[paramIndex(id)] = Math.max(0, Math.min(1, v))
  const slots = new Array(MAX_MOD_SLOTS).fill(null)
  ;(preset.mods ?? []).slice(0, MAX_MOD_SLOTS).forEach((m, i) => {
    slots[i] = { source: modSourceIndex(m.source), dest: paramIndex(m.dest), depth: m.depth, enabled: m.enabled }
  })
  const shapes = Array.from({ length: 8 }, (_, l) => preset.lfoShapes?.[l]?.length ? preset.lfoShapes[l] : defaultLfoShape())
  let fxOrder = preset.fxOrder ? preset.fxOrder.map(id => FX_IDS.indexOf(id)).filter(i => i >= 0) : DEFAULT_FX_ORDER.slice()
  if (fxOrder.length !== FX_IDS.length) fxOrder = DEFAULT_FX_ORDER.slice()

  send({ type: 'allNotesOff' })
  for (let i = 0; i < NUM_PARAMS; i++) send({ type: 'param', index: i, value: values[i] })
  for (let s = 0; s < MAX_MOD_SLOTS; s++) send({ type: 'mod', slot: s, state: slots[s] })
  for (let l = 0; l < 8; l++) send({ type: 'lfoShape', lfo: l, points: shapes[l] })
  send({ type: 'fxOrder', order: fxOrder })
  for (let o = 0; o < 3; o++) {
    const { t, mips } = tableFor(values, o)
    send({ type: 'wavetable', osc: o, frameSize: t.frameSize, numFrames: t.numFrames, mips })
  }

  // Events at block boundaries: block = floor(t * sr / 128); offs before ons.
  const events = []
  for (const [on, off, note, vel] of c.notes) {
    events.push({ block: Math.floor(on * SR / BLOCK), kind: 1, note, vel })
    events.push({ block: Math.floor(off * SR / BLOCK), kind: 0, note })
  }
  events.sort((a, b) => a.block - b.block || a.kind - b.kind)

  const blocks = Math.ceil(c.seconds * SR / BLOCK)
  const L = new Float32Array(blocks * BLOCK)
  const R = new Float32Array(blocks * BLOCK)
  const l = new Float32Array(BLOCK)
  const r = new Float32Array(BLOCK)
  let e = 0
  for (let b = 0; b < blocks; b++) {
    while (e < events.length && events[e].block === b) {
      const ev = events[e++]
      send(ev.kind ? { type: 'noteOn', note: ev.note, velocity: ev.vel } : { type: 'noteOff', note: ev.note })
    }
    proc.process([], [[l, r]])
    L.set(l, b * BLOCK)
    R.set(r, b * BLOCK)
  }
  return [L, R]
}

function wavFloat(L, R) {
  const n = L.length
  const buf = Buffer.alloc(44 + n * 8)
  buf.write('RIFF', 0); buf.writeUInt32LE(36 + n * 8, 4); buf.write('WAVE', 8)
  buf.write('fmt ', 12); buf.writeUInt32LE(16, 16); buf.writeUInt16LE(3, 20); buf.writeUInt16LE(2, 22)
  buf.writeUInt32LE(SR, 24); buf.writeUInt32LE(SR * 8, 28); buf.writeUInt16LE(8, 32); buf.writeUInt16LE(32, 34)
  buf.write('data', 36); buf.writeUInt32LE(n * 8, 40)
  for (let i = 0; i < n; i++) { buf.writeFloatLE(L[i], 44 + i * 8); buf.writeFloatLE(R[i], 48 + i * 8) }
  return buf
}

const fixtures = join(here, '..', 'fixtures')
mkdirSync(fixtures, { recursive: true })
for (const f of readdirSync(fixtures)) if (f.endsWith('.wav')) rmSync(join(fixtures, f))
for (const c of spec.cases) {
  const [L, R] = render(c)
  let peak = 0
  for (let i = 0; i < L.length; i++) peak = Math.max(peak, Math.abs(L[i]), Math.abs(R[i]))
  writeFileSync(join(fixtures, `${c.name}.wav`), wavFloat(L, R))
  console.log(`${c.name.padEnd(28)} peak ${peak.toFixed(3)}`)
}
